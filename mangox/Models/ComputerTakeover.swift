//
//  ComputerTakeover.swift
//  P18 批 3b: 人类接管 —— "人手在键鼠上，我就不动"的**判据**。
//
//  ⚠️ 这条判据不是安全边界(安全在 `ComputerActGuard`: 作用域/编号/三条恒拒), 而是**不添乱**:
//     模型正要点一个按钮时人接管了鼠标, 两边同时动 ⇒ 落到谁手里是随机的, 而"点错地方"的
//     代价可能是不可逆的(发出去的消息、付掉的订单)。所以判据只有一句: **人一动, 模型让路。**
//
//  ⚠️ 为什么是**时间窗**而不是"置一个待继续的标记": 后者会**死锁** —— helper 不认识
//     "用户说继续"这件事, 标记一旦置上就再也不会复位, 于是模型可以从那一刻起**永久罢工**,
//     而回执只说"人在用电脑"。时间窗的语义是"等这台机器静下来": 人真的在干活 ⇒ 一直有输入
//     ⇒ 一直刷新窗口 ⇒ 模型一直被挡在门外(正确); 人停了 ⇒ 窗口过后模型接着做(合理)。
//
//  ⚠️ 这里的判据**只看事实**(最后一次输入的时刻 + 此刻), 不猜"人是不是在看屏幕":
//     那件事机器判不出来, 判错的两个方向代价不对称(说"没人在" ⇒ 抢鼠标; 说"有人在"
//     ⇒ 白等), 所以宁可让它每次都能自己恢复。
//

import Foundation

enum ComputerTakeover {

    /// 最后一次人类输入之后, 这段时间内的动作一律不做。
    ///
    /// 取值不是拍的: ① **短于 2s** 时"人只是路过碰了一下触控板"根本挡不住模型下一步
    /// (模型一步通常 1~3s, 等它想完, 人早动完了); ② **长于 10s** 时人已经明显回到自己的活上,
    /// 模型却在无谓空等, 一步一个 10 秒会把整轮任务拖成"卡住了"。
    /// 6s 是"人真的在用电脑"这件事整体体现为"模型让路", 又不至于把一个正常任务拖散。
    ///
    /// ⚠️ 这个数只有一侧在读(App 侧不下发) —— 它跟"名单"不同, 改了不需要重启进程:
    ///    每次判定现读。
    static let quietSeconds: TimeInterval = 6

    /// 拒(`nil` = 可以做)。
    ///
    /// - Parameters:
    ///   - lastHumanInputAt: 监听装上以来**最后一次**人类输入的时刻(单调时钟)。从没人碰过 ⇒ `nil`。
    ///   - now: 此刻(同一个时钟)。
    ///   - installed: 监听到底装上没有。**没装上 ⇒ 放行** —— 拿不到事实时不许假装判断过;
    ///     同时回执里会明说"接管检测没装上"(见 `ComputerServer.takeoverCaveat`), 由人自己决定要不要紧。
    static func refusal(lastHumanInputAt: TimeInterval?,
                        now: TimeInterval,
                        installed: Bool) -> String? {
        guard installed, let human = lastHumanInputAt else { return nil }
        let quiet = now - human
        // 时钟只往前走 ⇒ `quiet < 0` 只可能是两次取了不同的时钟, 那时人刚动过 ⇒ 当"刚动过"。
        guard quiet < quietSeconds else { return nil }
        return "刚才有人动了鼠标 / 键盘 ⇒ 这次没动(界面一下都没动)。"
            + "人手还在键鼠上时我不抢 —— 你让我继续, 我下一步接着来。"
    }
}

//  ⚠️ 内容与 `SopInjection` 的解析是一套契约（`## 名字 · bundle · 版本` / 通则 / `###`）,
//     两边改一边就得改另一边; 冒烟 `T-SOP 手册本体` 那几条守着（覆盖全部 builtins、每节字数、
//     不写具体编号）。
//
//  写新一节的硬约束:
//    ⓪ **按任务线写**（2026-11-06）: 一节 = 若干 `### 任务`, 每条 = 编号步骤, **判据跟在步骤同一行**。
//       写成散文、或按知识分类（元素 / 动作 / 判据 / 禁忌）都不行 —— 那会把同一件事的步骤切碎，
//       模型得自己拼一条路出来。冒烟 `T-SOP 每节要写成任务线` 守着（带常驻反例自证）。
//    ① **单节 ≤ 700 字**（整份 ≤ 4500, 预算 `Tune.sopTotalCharLimit`）—— 它每轮都进提示词。
//    ② **没验过的步骤必须写 `未验：`** —— 点击不可逆, 含糊比不写更坏。
//    ③ **锚必须可判定**: role + 名字（`outline "文件夹"` / `值:"个人"`）, 不写"左上角那个按钮"
//       （模型看不见像素, 只看得见编号与名字）。
//    ④ **不写具体编号**（`#7`）: 编号每次 read 都变, 写死即过期数据。
//    ⑤ **不写账号 / 密码 / 邮箱地址 / 令牌**: 这段文本会进上下文, 也可能被分享。
//
//  结构（2026-11-06 第三次改；前两次都不对）：
//    - 0.2.2 按「AX 树长什么样」写 —— 那是界面结构说明，不是给人办事用的。
//    - 0.2.5 改成「人会说的事」，加了「看今天 / 建一条 / 删一条」，但骨架仍是「找 / 做 / 成 / 别」
//      四个抽屉 —— **只换了素材，没换结构**。那四个字是我自己造的口诀，不是 SOP 的标准段落
//      （标准是「目的 / 适用范围 / 步骤 / 记录」）。后果很硬：同一件事的步骤被切碎分到四处，
//      模型得自己拼；而「成」一个 App 只有一段，可一个 App 有四五件事（备忘录那段「成」
//      其实只覆盖"删一条"，建一条 / 追加 / 打开都没有判据）。
//    - 现在（boss 定）按**任务**切：每个 App 若干条 `### 任务`，每条 = 编号步骤，**每步的判据
//      跟在同一行**（`→ …` 或 `read 一次：…`），坑用 `✗` 挂在它所属的任务下面。
//      SOP 的判据只有一条：**换一个人照着做，能得到同样的结果** ⇒ 它必须是步骤序列，不是知识分类。
//      没做到的事写成「`### 某事 — 做不到`」，别混进步骤里。
//
//  数据来源:
//    · 结构（节点数/耗时/role/title 长什么样）→ `scripts/diag/ax_coverage_probe.sh`
//    · 每条场景能不能真做到 + 怎么算成了 → `scripts/diag/scenario_probe.sh`（14 条，真机跑）
//    两份读数都记在 `MEMORY-details` 的 P19 表与「场景回归」一节。
//


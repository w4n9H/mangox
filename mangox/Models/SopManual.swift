    - 编号每次 read、每次 act 之后**都会变** ⇒ 只记「怎么认」，别记编号。
    - act 的回执只给「变了什么 + 新 seq」⇒ 要动**没变过**的行必须重新 read；要动的正是那几行，直接用新编号。
    - read 最多 120 行，超了会写「还有 N 项未显示」—— 顶部工具栏已优先进来 ⇒ 别反复重读。
    - `op:"open"` 是**启动/激活 App**；打开**某个元素**（日期格、边栏、图标）用 act 的 `action:"open"`。

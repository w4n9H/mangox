    - read 有行数上限（各 App 不同，回执里会写明这次的上限是多少），超了会写「还有 N 项未显示」，重读也一样。
    - `op:"open"` 是**启动 / 激活 App**；带 `url` 就是**打开这个网址**（只认 http/https，不带 scheme 自动补，总是新开标签页）—— 浏览器换页**只有这一条路**。打开**某个元素**（日期格、边栏、图标）用 act 的 `action:"open"`。
    - 回执不可信（`open` 可能报「不支持」而界面真跳了，`confirm` 可能报成功而没落库）⇒ 重读看状态，不重发同一个动作。
    - 验证 = read 一次确认即可，别拿第二个数据源交叉核对（`osascript` / 数据库 / 手机 / 网页版）。
